"""Write validation/HISTORY.md from the committed history outputs (meta.json, replay.json, backtest.json).

    python scripts/history_report.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HIST = ROOT / "data" / "history"


def table(head, rows):
    out = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return out


def main():
    meta = json.loads((HIST / "meta.json").read_text(encoding="utf-8"))
    rep = json.loads((HIST / "replay.json").read_text(encoding="utf-8"))
    bt = json.loads((HIST / "backtest.json").read_text(encoding="utf-8"))
    claims = json.loads((ROOT / "claims.json").read_text(encoding="utf-8"))
    names = json.loads(sorted((ROOT / "data" / "snapshots").glob("*/network.json"))[-1].read_text(encoding="utf-8"))
    station = {f: x["station_id"] for f, x in names["lifts"].items()}
    nm = names["names"]
    L = [
        "# Lift Ledger: closure history replayed through the step-free graph",
        "",
        "Generated by `scripts/history_report.py` from `data/history/` (built by `ingest/history.py`, "
        "`scripts/history_replay.py`, `scripts/backtest.py`). Every number here is reproducible from committed files "
        "plus the four public archives below.",
        "",
        "**What these numbers are.** MBTA alerts record *reported* closures; MBTA may post or close an alert late. "
        "Today's station layouts are applied to past closures, so lifts replaced or added since 2024 are listed under "
        "topology drift. Nothing here is a forecast.",
        "",
        "## Sources",
        "",
        *table(["Collection", "ArcGIS item", "sha256"],
               [[k, v["item_id"], f"`{v['sha256'][:16]}…`"] for k, v in sorted(meta["sources"].items())]),
        "",
        f"MassDOT open data portal, owner MBTAHUB_ADMIN. The archive runs to the end of May 2026. "
        f"{meta['rows_used']:,} closure rows (effect_detail ELEVATOR_CLOSURE with a facility id) → {meta['alerts']:,} "
        f"alerts → {meta['windows']:,} closure windows on {meta['facilities_in_archive']} lifts. "
        f"{meta['windows'] - meta['windows_with_recorded_end']} windows have no recorded end (imputed, flagged). "
        f"{meta['out_of_scope_access_issue_rows']:,} ACCESS_ISSUE rows are out of scope. "
        "The portal writes Boston local time with a 'Z' suffix; LastLift reads it as local time (checked: the same "
        "alerts in LAMP and in MBTA's V3 API, which carry true offsets, differ from the portal by exactly the Eastern "
        "offset).",
        "",
        f"Second source: MBTA LAMP's alert archive ([parquet]({rep['lamp']['source']}), sha256 "
        f"`{rep['lamp']['sha256'][:16]}…`, from {rep['lamp']['from'][:7]}). LAMP is updated daily and records the end of "
        "long-running alerts the portal's monthly files never closed, and holds alerts they miss. Merged, portal first: "
        + ", ".join(f"{v:,} windows {k}" for k, v in rep["lamp"]["windows_by_source"].items())
        + f"; {claims['hist_windows_imputed']} windows still have no recorded end (imputed, flagged).",
        "",
        "## Ledger (since " + rep["from"] + ")",
        "",
        f"- Platform-directions that lost step-free access at least once: **{claims['hist_dirs_lost']}**.",
        f"- Lost platform-direction hours: **{claims['hist_lost_service_h']:,} in service hours** "
        f"({claims['hist_lost_calendar_h']:,} calendar hours).",
        f"- Share of lost service hours caused by a single lift: **{claims['hist_single_share'] * 100:.1f}%**. "
        f"The rest ({claims['hist_concurrent_service_h']:,} h) needed two or more lifts out at once: redundancy was "
        f"defeated {claims['hist_concurrent_losses']} times.",
        "",
        "Most hours lost, by platform-direction:",
        "",
        *table(["Platform-direction", "Station", "Service h", "Months with a loss", "Single-lift share"],
               [[k, nm.get(names["platform"][k.split(":")[0]]["station_id"], ""), round(v["svc_h"]),
                 len(v["months"]), f"{v['single_svc_h'] / v['svc_h'] * 100:.0f}%" if v["svc_h"] else "-"]
                for k, v in sorted(rep["platform_dirs"].items(), key=lambda kv: -kv[1]["svc_h"])[:12]]),
        "",
        "Lifts whose closure alone cost the most step-free service hours:",
        "",
        *table(["Lift", "Station", "Service h lost (alone)", "Available, last 12 months", "Closures, last 12 months",
                "Median closure (h)"],
               [[f, nm.get(station.get(f, ""), ""), round(x["single_svc_h"]), f"{x.get('avail_12m', 0) * 100:.1f}%",
                 x.get("outages_12m"), x.get("mttr_h")]
                for f, x in sorted(rep["lifts"].items(), key=lambda kv: -kv[1].get("single_svc_h", 0))[:12]]),
        "",
        "## Sensitivity (pre-registered in `eval/sensitivity.md`)",
        "",
        *table(["Imputed ends", "Episode gap (min)", "Platform-directions lost", "Calendar h", "Service h",
                "Single-lift share"],
               [[s["imputed"], s["gap_min"], s["dirs_lost"], f"{s['calendar_h']:,}", f"{s['service_h']:,}",
                 f"{s['single_share'] * 100:.1f}%"] for s in rep["sensitivity"]]),
        "",
        "Default: imputed ends = the alert's last modification (`low`), gap 30 minutes. `out` drops windows with no "
        "recorded end; `high` runs them to the end of the last archive month that still lists the alert.",
        "",
        "## 2025 cross-check between sources (H2)",
        "",
        *table(["2025 calendar platform-direction hours", "Hours"],
               [["Portal only, recorded ends (the planning probe measured 25,325)",
                 f"{rep['bracket_2025_calendar_h']['portal_recorded']:,}"],
                ["Portal only, open alerts run to the last month listing them",
                 f"{rep['bracket_2025_calendar_h']['portal_imputed_high']:,}"],
                ["LAMP only, recorded ends", f"{rep['bracket_2025_calendar_h']['lamp_recorded']:,}"],
                ["Merged (used everywhere), recorded ends", f"{rep['bracket_2025_calendar_h']['merged_recorded']:,}"]]),
        "",
        "The portal-only figure reproduces the probe within 1%. The probe's upper bound (414,000) ran every never-closed "
        "alert to the end of the year; LAMP shows when most of them actually closed, which is better evidence.",
        "",
        "Platform-direction service hours without step-free access, per year (merged; 2019 from LAMP only, 2026 to "
        "May):",
        "",
        *table(["Year", "Service h"], [[y, f"{h:,}"] for y, h in rep["lamp"]["yearly_service_h"].items()]),
        "",
        "## Out of sample: why LastLift makes no failure predictions",
        "",
        f"**H6 (negative result).** Ranking the {bt['h6']['lifts']} single-point-of-failure lifts by their 2024 history "
        "and comparing with the step-free hours each actually cost in 2025:",
        "",
        *table(["Ranking from 2024", "Spearman", "Precision of top 10"],
               [[k, v["spearman"], v["precision_at_10"]] for k, v in bt["h6"].items() if isinstance(v, dict)]),
        "",
        "History does not identify next year's costliest lifts, so LastLift shows historical frequencies only.",
        "",
        f"**H5 (monthly occurrence, rolling origin, {bt['h5']['folds']} folds, {bt['h5']['forecasts']:,} forecasts).** "
        f"Brier skill against the pooled base rate: {bt['h5']['skill']} (station-cluster bootstrap 95% "
        f"{bt['h5']['skill_ci95_station_bootstrap'][0]} to {bt['h5']['skill_ci95_station_bootstrap'][1]}). "
        f"The bar set in advance was skill ≥ 0.3 and every bin with at least 100 forecasts within 0.08: "
        f"**{'met' if bt['h5']['calibrated'] and bt['h5']['skill'] >= 0.3 else 'not met'}**, so no forecast is shown "
        "anywhere.",
        "",
        *table(["Predicted", "n", "Mean predicted", "Observed", "Within 0.08"],
               [[f"{b['bin'][0]:.1f}–{b['bin'][1]:.1f}", b["n"], b["pred"], b["obs"],
                 "yes" if abs(b["pred"] - b["obs"]) <= 0.08 else "no"] for b in bt["h5"]["reliability"]]),
        "",
        "**What the history does support: k.** Share of months in which a platform-direction lost step-free access: "
        f"**{bt['k_validation']['share_of_months_with_loss']['k1'] * 100:.1f}%** for single-lift platforms (k = 1), "
        f"**{bt['k_validation']['share_of_months_with_loss']['k2plus'] * 100:.1f}%** for k ≥ 2 "
        f"(over {bt['k_validation']['months']} months).",
        "",
        "## Reliability with each lift's own outage rate (G5)",
        "",
        f"With q = 1 − availability over the last 12 archive months, {claims['rel_emp_dirs_over_5pct']} of "
        f"{claims['rel_emp_dirs']} lift-dependent platform-directions would be without step-free access more than 5% "
        f"of the time; across the network, {rep['monte_carlo_empirical']['mean'] * 100:.2f}% of journeys between "
        f"stations stay step-free (Monte-Carlo, {rep['monte_carlo_empirical']['samples']} samples, 95% "
        f"{rep['monte_carlo_empirical']['ci95'][0] * 100:.2f}–{rep['monte_carlo_empirical']['ci95'][1] * 100:.2f}%).",
        "",
        "## Topology drift (H8)",
        "",
        f"- In the archive but not in today's GTFS elevators ({len(meta['drift']['archive_not_in_gtfs'])}): "
        + ", ".join(meta["drift"]["archive_not_in_gtfs"]),
        f"- In the archive but not in the step-free model ({len(meta['drift']['archive_not_in_model'])}): "
        + ", ".join(meta["drift"]["archive_not_in_model"]),
        f"- In the model but never closed in the archive ({len(meta['drift']['model_never_in_archive'])}): "
        + ", ".join(meta["drift"]["model_never_in_archive"]),
        "",
        "## Historical gold (H7)",
        "",
        "20 archived closures (seed in `eval/sampling.json`) are labelled blind by the author from MBTA's own text "
        "(ids and text hashes in `validation/history_gold_ids.csv`), then compared with the model's verdict for the "
        "lifts closed at that moment (`scripts/history_gold.py --score`). "
        + (f"Result: {claims['hist_gold_agree']}/{claims['hist_gold_scored']} agree "
           f"(Wilson 95% {claims['hist_gold_agree_wilson95']})." if "hist_gold_scored" in claims
           else "Status: awaiting the author's labels."),
        "",
    ]
    (ROOT / "validation" / "HISTORY.md").write_text("\n".join(L), encoding="utf-8", newline="\n")
    print("wrote validation/HISTORY.md")


if __name__ == "__main__":
    main()
