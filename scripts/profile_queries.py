"""Write FalkorDB execution plans (GRAPH.EXPLAIN) and profiles (GRAPH.PROFILE, on a private copy of the demo graph)
for the main read queries to docs/profiles/, so the README can show how FalkorDB runs them.

    python scripts/profile_queries.py
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from fastapi.testclient import TestClient  # noqa: E402

from lastlift import db, main  # noqa: E402

QUERIES = ["Q_MAXFLOW", "Q_LOST_NOW", "Q_NEWLY_LAST", "Q_PRIORITY", "Q_REACHES_FROM", "Q_CRITICAL_PAIRS",
           "Q_LIFT_BLAST", "Q_STATION_SEARCH"]


def main_() -> int:
    out = ROOT / "docs" / "profiles"
    out.mkdir(parents=True, exist_ok=True)
    main.PLAN_LIMIT_PER_MIN = 1000
    with TestClient(main.app) as c:
        version = db.module_version()
        index = ["# FalkorDB query plans and profiles", "",
                 f"FalkorDB module {version}. Generated by `scripts/profile_queries.py`; the API serves the same at "
                 "`GET /v1/queries/{id}/plan?mode=explain|profile`. Profiles run on a private copy of the demo graph; "
                 "times are milliseconds on the shared FalkorDB Cloud instance used for development, so they vary "
                 "between runs.", ""]
        for qid in QUERIES:
            ex = c.get(f"/v1/queries/{qid}/plan").json()
            pr = c.get(f"/v1/queries/{qid}/plan", params={"mode": "profile"}).json()
            text = [f"# {qid}", "", "Query:", "", ex["query"], "", f"Parameters: {ex['params']}", "",
                    "EXPLAIN:", "", *ex["plan"], "", "PROFILE:", "", *pr["plan"], ""]
            (out / f"{qid}.txt").write_text("\n".join(text), encoding="utf-8", newline="\n")
            index.append(f"- [{qid}]({qid}.txt)")
            print(qid, "ok")
        (out / "README.md").write_text("\n".join(index) + "\n", encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main_())
